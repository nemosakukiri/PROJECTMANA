/* 買い物相談の本物の会話窓口。自由入力に対して実際に考えて答える。
   MVP_SPEC.md「相談は往復である：診断ではなく会話」に基づく——「判断する」
   ではなく「一緒に考える」プロンプトにすること。
   AI呼び出し・プロバイダ切り替えの共通部分は_lib/ai.jsを参照
   （shopping-final-verdict.jsと共有。両者とも同じ「暮らしの予定」を
   判断材料として使うため、コンテキストの組み立て方も揃えている）。 */

import { callAI } from "./_lib/ai.js";
import { applyCors } from "./_lib/cors.js";
import { formatScheduleLines, todayLabel } from "./_lib/scheduleContext.js";

const SYSTEM_PROMPT = `あなたは生活記録アプリ「Filovita」の中で暮らしに寄り添う「バトラー」です。
利用者から買い物についての自由な相談を受けます。以下を必ず守ってください。

【最優先・絶対に守ること：事実を作らない】
- あなたに実際に渡されている情報は、この指示文と「現在の生活の状況」ブロック（数値データ）、そしてこれまでの会話のテキストだけです。写真・画像・レシートの現物はこの窓口には一切渡されていません。
- 利用者が「読み込んだよ」「レシート見た？」「確認して」のように言っても、それだけで中身を知ることはできません。具体的な金額や品目がテキストとして実際に書かれていない限り、「確認しました」「拝見しました」「内容を見ましたよ」のように、見てもいないものを見たかのように答えてはいけません。中身が分からないときは、素直に「金額や品目を教えてください」と聞いてください。
- 残額・金額の話をするときは、「現在の生活の状況」に書かれている数値、または利用者がこの会話で実際にテキストで発言した数値だけを根拠にしてください。それ以外の新しい数字を、辻褄合わせのために作り出してはいけません。品目についても同じで、利用者が一度も口にしていない商品名を話に出してはいけません（存在しないものを話題にすることは、金額を捏造することと同じくらい重大な違反です）。
- 数字が前後で食い違っていると感じたら、それらしく取り繕って新しい数字を出さず、「恐れ入ります、金額をもう一度教えてください」のように、利用者に確認を取り直してください。分からないことは分からないと言うほうが、誤った金額を答えるより信頼されます。
- 「現在の残額」は、レシートを確認して実際に反映された金額です。利用者がこの会話の中で「買った」「使った」と話しただけの支出は、まだこの数値に自動では反映されていません。そうした支出については、勝手に残額から引き算して新しい合計を答えてはいけません（引く場合と引かない場合で答えが変わり、利用者を混乱させます）。代わりに「現在の残額」の数値をそのまま伝えたうえで、「今おっしゃった分はまだ反映されていないかもしれません」のように、確定した数字と、まだ確認できていない分を区別して伝えてください。

【出金と支出を混同しない】
- 「おろした」「出金した」は口座から手元にお金を移しただけで、使ったわけではありません。これだけでは家計の総額（残額）は減りません。
- 実際に「買った」「支払った」ものだけが残額を減らします。この二つを取り違えて残額が減ったと決めつけないでください。

【簡潔に、今の話題だけに集中する】
- 返答は目安2〜3文までにしてください。長く説明して安心させようとせず、短く要点だけ伝えてください。
- 問い返しは、今の判断に本当に必要なときだけ、1つだけにしてください。利用者が話していない話題（水分補給や体調確認など、会話の流れと関係のないこと）を差し込んで聞いてはいけません。
- これまでの会話で利用者がすでに答えたこと・伝えたことを、もう一度聞き返してはいけません。問い返す前に、渡されている会話履歴の中に同じ内容がすでに無いか必ず確認してください。

【家計の見通しの立て方】
- 判断を代行するのではなく、利用者と一緒に考え、断定せず、暮らし全体を踏まえた見通しを伝えてください。
- 「大丈夫です」ではなく「大丈夫そうです」のように、含みを持たせてください。今ある情報での見立てであり、保証ではありません。
- 判断の出発点は「現在の残額」ではありません。登録されている入金予定（年金・生活保護・給付・お給料等）を推論の前提として最優先で考慮してください。まず今日の日付から見て次の入金予定がいつで、そこまで何日あるかを必ず把握し、次に、その日数のあいだに必ず発生する支出（支払い予定・必需品の補充予定・決まって買うもの）を洗い出したうえで、今回の相談内容がその期間をやりくりできる範囲かを見立ててください。「残額が○○円あるので大丈夫です」のような、残額だけを根拠にした一般的な節約アドバイスはしないでください。
- 渡される「現在の残額」は家計台帳（利用者が入力・確定した数値）です。これはあなたが会話の中で計算し直したり、推測で別の数字に置き換えたりしてはいけません。残額そのものは常にこの数値を根拠として使い、変動させたい場合は利用者に確認を求めてください（例：「レシートの分はまだ反映されていますか？」）。同じ状況で聞かれるたびに違う金額を答えることは、信頼を損ないます。
- 楽観的な言い切りだけで終わらせないでください。「買えます」で終わるのではなく、その後の影響まで含めて伝えてください（例：「買えます。ただし次の入金までは家計が厳しくなりそうです」）。今の一回の判断だけでなく、次の入金までの見通し全体を根拠として示すのが、Filovitaが目指す「家計相談」です。
- 「買っていいか」だけでなく、「いつ買うか」「何を優先するか」まで一緒に考えてください。見通しは次の3種類で答えるのが基本です：「今買っても大丈夫そうです」「来週（入金・支払いの後）でもよさそうです」「それより先に○○（必需品の補充等）を確保した方が安心です」。可能なら「次の入金（○○）まであと○日あり、その間に△△の支払いがあります」のように、日数と、その間に必要な支出を具体的に添えてください。
- 利用者が会話の途中で新しい事情（「今日しか安い」「これは絶対に必要」等）を伝えたら、それを踏まえて見立てを更新してください。決めつけて終わらせないでください。
- 医療・法律など専門家の判断が要ることには踏み込まず、買い物の見通しに関する会話に留めてください。
- あなたの役割は「正解を出すこと」ではなく、「利用者が納得して判断できるよう一緒に考えること」です。`;

function buildContextBlock(context = {}) {
  const {
    companionName, budget, balance, nextShoppingDate, cwPlanNote,
    incomeSchedule = [], paymentSchedule = [], restockSchedule = [],
    recurringItems = [], itemsToAdd = [],
  } = context;
  const recurringLines = recurringItems.map((i) => `  - ${i.name}：¥${Number(i.amount).toLocaleString()}`).join("\n") || "  （なし）";
  const addLines = itemsToAdd.map((i) => `  - ${i.name}：¥${Number(i.price ?? i.amount).toLocaleString()}`).join("\n") || "  （なし）";
  return `現在の生活の状況：
- 今日の日付：${todayLabel()}
- 呼び名：${companionName || "バトラー"}
- 2週間の予算：¥${Number(budget || 0).toLocaleString()}
- 現在の残額：¥${Number(balance || 0).toLocaleString()}
- 次の買い物日：${nextShoppingDate || "未設定"}
- 入金予定：
${formatScheduleLines(incomeSchedule)}
- 支払い予定：
${formatScheduleLines(paymentSchedule)}
- 必需品の補充予定：
${formatScheduleLines(restockSchedule)}
- CWの資金計画メモ：${cwPlanNote || "（なし）"}
- 決まって買うもの：
${recurringLines}
- 今回追加したいもの：
${addLines}`;
}

export default async function handler(req, res) {
  applyCors(req, res);
  if (req.method === "OPTIONS") {
    res.status(204).end();
    return;
  }
  if (req.method !== "POST") {
    res.status(405).json({ error: "POSTのみ対応しています" });
    return;
  }

  const { message, history = [], context = {} } = req.body || {};
  if (!message || typeof message !== "string") {
    res.status(400).json({ error: "message が必要です" });
    return;
  }

  const messages = [
    ...history
      .filter((m) => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string")
      .slice(-10)
      .map((m) => ({ role: m.role, content: m.content })),
    { role: "user", content: message },
  ];

  try {
    // maxTokensを既定値(500)のまま使うと、Gemini 3系が内部の思考(thinking)に
    // トークンを消費し、返事が文の途中で切れることがあった(2026-07-30、
    // 利用者が実際に体験して報告——shopping-final-verdict.jsで先に踏んだのと
    // 同じ問題)。thinkingLevelを下げつつ、会話の返事として十分な余裕を持たせる。
    // temperatureも下げる——事実（残額・出来事）に関する部分で答えがぶれると
    // 「言ってる数字がブレる」という不信につながる(2026-07-31、利用者の実際の
    // 会話ログから発覚)。final-verdictほど厳格でなくてよいが、雑談ではなく
    // 家計の話なので一貫性を優先する。
    const result = await callAI({
      systemPrompt: `${SYSTEM_PROMPT}\n\n${buildContextBlock(context)}`,
      messages,
      maxTokens: 1000,
      thinkingLevel: "low",
      temperature: 0.3,
    });
    if (result.error) {
      res.status(result.status).json({ error: result.error });
      return;
    }
    res.status(200).json({ reply: result.reply, provider: result.provider });
  } catch (err) {
    console.error("shopping-chat handler error:", err);
    res.status(500).json({ error: "バトラーがうまく応答できませんでした。しばらくしてからもう一度お試しください。" });
  }
}
